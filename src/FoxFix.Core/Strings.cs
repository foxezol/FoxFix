    private static readonly ResourceManager Manager = new("FoxFix.Core.Resources.Strings", typeof(Strings).Assembly);

    public const string Turkish = "tr";

    public const string English = "en";

    /// <summary>The language of every text the program shows. Turkish is the default (Strings.resx); English is Strings.en.resx.</summary>
    public static string Language { get; private set; } = Turkish;

    public static bool IsEnglish => Language == English;

    /// <summary>"tr" or "en"; anything else is taken as Turkish. Also sets how numbers and dates are written.</summary>
    public static void SetLanguage(string? code)
    {
        Language = string.Equals(code, English, StringComparison.OrdinalIgnoreCase) ? English : Turkish;
        var culture = CultureInfo.GetCultureInfo(IsEnglish ? "en-US" : "tr-TR");
        CultureInfo.DefaultThreadCurrentCulture = culture;
        CultureInfo.DefaultThreadCurrentUICulture = culture;
        CultureInfo.CurrentCulture = culture;
        CultureInfo.CurrentUICulture = culture;
    }

    public static bool IsKnownLanguage(string? code) =>
        string.Equals(code, Turkish, StringComparison.OrdinalIgnoreCase) || string.Equals(code, English, StringComparison.OrdinalIgnoreCase);

    public static string Get(string key)
    {
        // The satellite resource for "en" is used when English is chosen, the default (Turkish) resource otherwise.
        return Manager.GetString(key, CultureInfo.GetCultureInfo(Language))
            ?? throw new InvalidOperationException($"Eksik metin kaynağı / Missing text resource: {key}");
    }

    /// <summary>The text in one language whatever is chosen now (used by tests to compare the two).</summary>
    public static string GetIn(string key, string language) =>
        Manager.GetString(key, CultureInfo.GetCultureInfo(language)) ?? throw new InvalidOperationException($"Missing text resource: {key}");

    /// <summary>Every key of the resource file (all of them exist in both languages).</summary>
    public static IEnumerable<string> AllKeys() =>
        typeof(Strings).GetFields(System.Reflection.BindingFlags.Public | System.Reflection.BindingFlags.Static)
            .Where(f => f.IsLiteral && f.FieldType == typeof(string) && f.Name != nameof(Turkish) && f.Name != nameof(English))
            .Select(f => (string)f.GetRawConstantValue()!);

    /// <summary>A finding text for a device kind: {0} is the kind name.</summary>
    public static string VerdictFor(string key, string kindName) => string.Format(CultureInfo.CurrentCulture, Get(key), kindName);

    public static string Format(string key, params object[] args)
    {
        return string.Format(CultureInfo.CurrentCulture, Get(key), args);
    }
